#!/usr/bin/env python3
"""Build the `preset-standard` override that routes subagents to the GLM gateway.

Why an override instead of a simple config patch
------------------------------------------------
The Web bundle *disables* the Host-plane `tool-subagent` / `tool-subagent-fork`
rows and lets each **agent preset** mount its own. So patching `id: tool-subagent`
at the top level only touches a disabled row and has no effect. DSH's own
`editing-cordis-compositions` skill states the supported route:

    Override the declaration by its Loader row id instead of inserting.
    The override replaces the complete `config`, so restate `id`, `plugins`
    and every other field the shipped file carries.

That means the whole `plugins` list must be restated. This script copies it
verbatim from the shipped preset (preserving `!!js` expressions and comments)
and injects `agentOptions` into the two delegation tools, so no line is
hand-transcribed and nothing else changes.

Re-run this script after a DSH upgrade to pick up the new shipped preset:
    python build_preset_override.py <standard.patch.yml> <cordis.patch.yml>
"""
from __future__ import annotations

import io
import sys

MARK_BEGIN = "# ── BEGIN generated preset-standard override ──"
MARK_END = "# ── END generated preset-standard override ──"

# Child route forced onto every delegation tool: the internal GLM gateway.
AGENT_OPTIONS = [
    "agentOptions:",
    "  provider: zgci",
    "  model: glm",
    "  maxTokens: 32768",
]


def extract_preset_entry(src_path: str) -> list[str]:
    """Return the `- id: preset-standard` entry, de-indented 4 spaces."""
    lines = io.open(src_path, encoding="utf-8").read().splitlines()
    start = None
    for i, line in enumerate(lines):
        if line.strip() == "- id: preset-standard":
            start = i
            break
    if start is None:
        raise SystemExit(f"could not find '- id: preset-standard' in {src_path}")

    block = lines[start:]
    while block and block[-1].strip() == "":
        block.pop()

    out: list[str] = []
    for line in block:
        if line.strip() == "":
            out.append("")
            continue
        if not line.startswith("    "):
            raise SystemExit(f"unexpected indentation (expected 4+ spaces): {line!r}")
        out.append(line[4:])
    return out


def inject_agent_options(entry: list[str], tool_id: str) -> tuple[list[str], bool]:
    """Insert AGENT_OPTIONS at the end of one tool entry's `config:` block."""
    start = None
    for i, line in enumerate(entry):
        if line.strip() == f"- id: {tool_id}":
            start = i
            break
    if start is None:
        raise SystemExit(f"{tool_id}: entry not found")

    # The entry ends at the next sibling row (`- id:` at the same indent) or EOF.
    row_indent = len(entry[start]) - len(entry[start].lstrip())
    end = len(entry)
    for j in range(start + 1, len(entry)):
        line = entry[j]
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip())
        if indent == row_indent and line.strip().startswith("- id: "):
            end = j
            break

    # Locate `config:` inside the entry (the first line that is exactly config:).
    config_at = None
    for j in range(start + 1, end):
        if entry[j].strip() == "config:":
            config_at = j
            break
    if config_at is None:
        raise SystemExit(f"{tool_id}: no config block found")
    config_indent = len(entry[config_at]) - len(entry[config_at].lstrip())
    child_indent = config_indent + 2

    # Copy everything up to (and including) the config block's existing children,
    # then append the options. Intervening keys such as `name:` are preserved.
    out = entry[: config_at + 1]
    k = config_at + 1
    while k < end:
        line = entry[k]
        if line.strip() == "":
            break
        if len(line) - len(line.lstrip()) < child_indent:
            break
        out.append(line)
        k += 1
    for opt in AGENT_OPTIONS:
        out.append(" " * child_indent + opt)
    out.extend(entry[k:])
    return out, True


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, dst = sys.argv[1], sys.argv[2]

    entry = extract_preset_entry(src)
    entry, ok_spawn = inject_agent_options(entry, "tool-subagent")
    entry, ok_fork = inject_agent_options(entry, "tool-subagent-fork")
    if not (ok_spawn and ok_fork):
        raise SystemExit(f"injection failed (spawn={ok_spawn}, fork={ok_fork})")

    generated = [
        MARK_BEGIN,
        "# Generated by scripts/build_preset_override.py from the shipped",
        "# @deepseek-ai/dsh-web-app presets/standard.patch.yml. Everything below",
        "# 'plugins:' is copied verbatim from that file except the injected",
        "# `agentOptions`, which routes child agents to the internal GLM gateway.",
        "# The Loader row id is preset-standard, so this REPLACES the shipped",
        "# config wholesale (DSH requires restating id/plugins/order).",
        "# Re-run the generator after a DSH upgrade.",
        MARK_END,
    ] + entry

    text = "\n".join(generated) + "\n"
    io.open(dst, "w", encoding="utf-8", newline="\n").write(text)
    print(f"wrote {dst}: {len(entry)} preset lines, agentOptions injected into both tools")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
